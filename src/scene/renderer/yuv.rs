//! The GPU conversion of the YUV 4:2:0 planes of a video into RGBA.
//!
//! The video decoders hand out the frames as planar YUV 4:2:0: the CPU
//! does not have to turn them into RGB, the GPU does.  The three planes
//! are uploaded as ordinary `R8Unorm` textures and a small render pass
//! combines them into the RGBA texture the wallpaper samples.
//!
//! The pass writes into an *sRGB* texture, exactly like the RGBA upload
//! path does today: the shader therefore decodes the gamma encoded value
//! it computes, and the hardware encodes it again when it stores it.  The
//! bytes that end up in the texture are the ones the `swscale`
//! conversion produced, and the wallpaper samples them exactly like it
//! samples them today.

use pkg_parser::pkg_parser::video_parser::YuvColorspace;
use wgpu::*;

use crate::scene::renderer::error_scope;

/// The shader that combines the planes of a frame into RGBA.
const SHADER: &str = include_str!("shader/yuv2rgb.wgsl");

/// The parameters of the conversion: the matrix of the colour space.
///
/// The layout matches the `YuvParams` structure of the shader.
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq, bytemuck::Pod, bytemuck::Zeroable)]
struct YuvParams {
    /// The scale of the luma.
    y_scale: f32,
    /// The offset of the luma.
    y_offset: f32,
    /// The offset of the U plane.
    u_offset: f32,
    /// The offset of the V plane.
    v_offset: f32,
    /// The coefficient of the V plane in the red channel.
    crv: f32,
    /// The coefficient of the U plane in the green channel.
    cgu: f32,
    /// The coefficient of the V plane in the green channel.
    cgv: f32,
    /// The coefficient of the U plane in the blue channel.
    cbu: f32,
}

impl YuvParams {
    /// The parameters of the conversion of a colour space.
    fn new(colorspace: YuvColorspace) -> Self {
        let coefficients = colorspace.coefficients();
        Self {
            y_scale: coefficients.y_scale,
            y_offset: coefficients.y_offset,
            u_offset: coefficients.u_offset,
            v_offset: coefficients.v_offset,
            crv: coefficients.crv,
            cgu: coefficients.cgu,
            cgv: coefficients.cgv,
            cbu: coefficients.cbu,
        }
    }
}

/// The conversion of the YUV planes of a video into RGBA.
///
/// The converter owns the pipeline of the pass; every animated texture
/// owns its own [`YuvTarget`], which holds the planes and the bind group
/// of the pass.
pub struct YuvConverter {
    /// The pipeline of the conversion pass.
    pipeline: RenderPipeline,
    /// The layout of the bind group of the pass.
    layout: BindGroupLayout,
}

impl YuvConverter {
    /// Create the converter.
    ///
    /// Returns `None` when the shader could not be compiled: the caller
    /// then converts the frames on the CPU instead.
    pub fn new(device: &Device) -> Option<Self> {
        let built = error_scope::validation_scope(device, || {
            let shader = device.create_shader_module(ShaderModuleDescriptor {
                label: Some("yuv2rgb.shader"),
                source: ShaderSource::Wgsl(SHADER.into()),
            });

            let layout = device.create_bind_group_layout(&BindGroupLayoutDescriptor {
                label: Some("yuv2rgb.layout"),
                entries: &[
                    plane_entry(0),
                    plane_entry(1),
                    plane_entry(2),
                    BindGroupLayoutEntry {
                        binding: 3,
                        visibility: ShaderStages::FRAGMENT,
                        ty: BindingType::Buffer {
                            ty: BufferBindingType::Uniform,
                            has_dynamic_offset: false,
                            min_binding_size: None,
                        },
                        count: None,
                    },
                ],
            });

            let pipeline_layout = device.create_pipeline_layout(&PipelineLayoutDescriptor {
                label: Some("yuv2rgb.pipeline_layout"),
                bind_group_layouts: &[&layout],
                immediate_size: 0,
            });

            let pipeline = device.create_render_pipeline(&RenderPipelineDescriptor {
                label: Some("yuv2rgb.pipeline"),
                layout: Some(&pipeline_layout),
                vertex: VertexState {
                    module: &shader,
                    entry_point: Some("vs_main"),
                    compilation_options: Default::default(),
                    // The fullscreen triangle is generated by the shader.
                    buffers: &[],
                },
                primitive: PrimitiveState {
                    topology: PrimitiveTopology::TriangleList,
                    strip_index_format: None,
                    front_face: FrontFace::Ccw,
                    cull_mode: None,
                    unclipped_depth: false,
                    polygon_mode: PolygonMode::Fill,
                    conservative: false,
                },
                depth_stencil: None,
                multisample: MultisampleState {
                    count: 1,
                    mask: !0,
                    alpha_to_coverage_enabled: false,
                },
                fragment: Some(FragmentState {
                    module: &shader,
                    entry_point: Some("fs_main"),
                    compilation_options: Default::default(),
                    targets: &[Some(ColorTargetState {
                        // The texture the wallpaper samples is an sRGB
                        // one: the hardware encodes the value of the
                        // fragment when it stores it.
                        format: TextureFormat::Rgba8UnormSrgb,
                        blend: None,
                        write_mask: ColorWrites::all(),
                    })],
                }),
                multiview_mask: None,
                cache: None,
            });

            (pipeline, layout)
        });

        match built {
            Ok((pipeline, layout)) => Some(Self { pipeline, layout }),
            Err(error) => {
                log::error!("the YUV conversion shader could not be compiled: {error}");
                None
            }
        }
    }

    /// Create the planes and the bind group of an animated texture.
    ///
    /// The planes have the size of the frame: the luma plane is as big as
    /// the frame, the two chroma planes half the width and half the
    /// height.
    pub fn create_target(&self, device: &Device, width: u32, height: u32) -> YuvTarget {
        let width = width.max(1);
        let height = height.max(1);
        let chroma_width = width.div_ceil(2);
        let chroma_height = height.div_ceil(2);

        let y = create_plane(device, width, height);
        let u = create_plane(device, chroma_width, chroma_height);
        let v = create_plane(device, chroma_width, chroma_height);

        let y_view = y.create_view(&Default::default());
        let u_view = u.create_view(&Default::default());
        let v_view = v.create_view(&Default::default());

        let params = device.create_buffer(&BufferDescriptor {
            label: Some("yuv2rgb.params"),
            size: std::mem::size_of::<YuvParams>() as u64,
            usage: BufferUsages::UNIFORM | BufferUsages::COPY_DST,
            mapped_at_creation: false,
        });

        let bind_group = device.create_bind_group(&BindGroupDescriptor {
            label: Some("yuv2rgb.bind_group"),
            layout: &self.layout,
            entries: &[
                BindGroupEntry {
                    binding: 0,
                    resource: BindingResource::TextureView(&y_view),
                },
                BindGroupEntry {
                    binding: 1,
                    resource: BindingResource::TextureView(&u_view),
                },
                BindGroupEntry {
                    binding: 2,
                    resource: BindingResource::TextureView(&v_view),
                },
                BindGroupEntry {
                    binding: 3,
                    resource: BindingResource::Buffer(BufferBinding {
                        buffer: &params,
                        offset: 0,
                        size: None,
                    }),
                },
            ],
        });

        YuvTarget {
            y,
            u,
            v,
            bind_group,
            params,
        }
    }

    /// Record the conversion of the planes into the target texture.
    ///
    /// The pass fills the whole target with a fullscreen triangle.
    pub fn record(&self, encoder: &mut CommandEncoder, target: &YuvTarget, view: &TextureView) {
        let mut pass = encoder.begin_render_pass(&RenderPassDescriptor {
            label: Some("yuv2rgb.pass"),
            color_attachments: &[Some(RenderPassColorAttachment {
                view,
                depth_slice: None,
                resolve_target: None,
                ops: Operations {
                    load: LoadOp::Clear(Color {
                        r: 0.0,
                        g: 0.0,
                        b: 0.0,
                        a: 0.0,
                    }),
                    store: StoreOp::Store,
                },
            })],
            ..Default::default()
        });

        pass.set_pipeline(&self.pipeline);
        pass.set_bind_group(0, &target.bind_group, &[]);
        // The fullscreen triangle: three vertices, one instance.
        pass.draw(0..3, 0..1);
    }
}

/// The planes of an animated texture and the bind group of the pass.
pub struct YuvTarget {
    /// The luma plane: as big as the frame.
    y: Texture,
    /// The U plane: half the width and half the height of the frame.
    u: Texture,
    /// The V plane: half the width and half the height of the frame.
    v: Texture,
    /// The bind group of the pass.
    bind_group: BindGroup,
    /// The uniform buffer with the matrix of the colour space.
    params: Buffer,
}

impl YuvTarget {
    /// Upload the planes of a frame and the matrix of its colour space.
    pub fn upload(&self, queue: &Queue, y: &[u8], u: &[u8], v: &[u8], colorspace: YuvColorspace) {
        write_plane(queue, &self.y, y);
        write_plane(queue, &self.u, u);
        write_plane(queue, &self.v, v);

        let params = YuvParams::new(colorspace);
        queue.write_buffer(&self.params, 0, bytemuck::bytes_of(&params));
    }
}

/// The description of one plane in the bind group of the pass.
fn plane_entry(binding: u32) -> BindGroupLayoutEntry {
    BindGroupLayoutEntry {
        binding,
        visibility: ShaderStages::FRAGMENT,
        ty: BindingType::Texture {
            sample_type: TextureSampleType::Float { filterable: true },
            view_dimension: TextureViewDimension::D2,
            multisampled: false,
        },
        count: None,
    }
}

/// Create the texture of one plane of a frame.
fn create_plane(device: &Device, width: u32, height: u32) -> Texture {
    device.create_texture(&TextureDescriptor {
        label: Some("yuv plane"),
        size: Extent3d {
            width,
            height,
            depth_or_array_layers: 1,
        },
        mip_level_count: 1,
        sample_count: 1,
        dimension: TextureDimension::D2,
        format: TextureFormat::R8Unorm,
        usage: TextureUsages::TEXTURE_BINDING | TextureUsages::COPY_DST,
        view_formats: &[],
    })
}

/// Upload the pixels of one plane into its texture.
fn write_plane(queue: &Queue, texture: &Texture, pixels: &[u8]) {
    let width = texture.width();
    let height = texture.height();

    queue.write_texture(
        TexelCopyTextureInfo {
            texture,
            mip_level: 0,
            origin: Origin3d::ZERO,
            aspect: TextureAspect::All,
        },
        pixels,
        TexelCopyBufferLayout {
            offset: 0,
            bytes_per_row: Some(width),
            rows_per_image: None,
        },
        Extent3d {
            width,
            height,
            depth_or_array_layers: 1,
        },
    );
}

#[cfg(test)]
mod tests {
    use pkg_parser::pkg_parser::video_parser::yuv::yuv420_to_rgba;
    use pkg_parser::pkg_parser::video_parser::{YuvMatrix, YuvRange};

    use super::*;

    /// The colour spaces the tests run through.
    fn colorspaces() -> [YuvColorspace; 4] {
        [
            YuvColorspace::new(YuvMatrix::Bt601, YuvRange::Limited),
            YuvColorspace::new(YuvMatrix::Bt601, YuvRange::Full),
            YuvColorspace::new(YuvMatrix::Bt709, YuvRange::Limited),
            YuvColorspace::new(YuvMatrix::Bt709, YuvRange::Full),
        ]
    }

    /// The conversion the shader does, written with the textbook
    /// formula.
    ///
    /// The luma and the two chroma planes are combined with the Kr, Kg
    /// and Kb coefficients of the colour space; the chroma is sampled
    /// with the nearest neighbour, like the shader does.
    fn reference(
        width: u32,
        height: u32,
        y: &[u8],
        u: &[u8],
        v: &[u8],
        colorspace: YuvColorspace,
    ) -> Vec<u8> {
        let (kr, kb) = match colorspace.matrix() {
            YuvMatrix::Bt601 => (0.299_f32, 0.114_f32),
            YuvMatrix::Bt709 => (0.2126_f32, 0.0722_f32),
        };
        let kg = 1.0 - kr - kb;
        let (y_scale, y_offset, chroma_scale) = match colorspace.range() {
            YuvRange::Limited => (255.0 / 219.0, 16.0, 255.0 / 224.0),
            YuvRange::Full => (1.0, 0.0, 1.0),
        };

        let mut pixels = Vec::with_capacity((width * height * 4) as usize);
        for row in 0..height {
            for column in 0..width {
                let luma = y[(row * width + column) as usize] as f32;
                let chroma_row = (row / 2) * (width / 2);
                let blue = u[(chroma_row + column / 2) as usize] as f32;
                let red = v[(chroma_row + column / 2) as usize] as f32;

                let scaled = y_scale * (luma - y_offset);
                let rgb = [
                    scaled + chroma_scale * 2.0 * (1.0 - kr) * (red - 128.0),
                    scaled
                        - chroma_scale * 2.0 * kb * (1.0 - kb) / kg * (blue - 128.0)
                        - chroma_scale * 2.0 * kr * (1.0 - kr) / kg * (red - 128.0),
                    scaled + chroma_scale * 2.0 * (1.0 - kb) * (blue - 128.0),
                ];

                for value in rgb {
                    pixels.push(value.clamp(0.0, 255.0) as u8);
                }
                pixels.push(255);
            }
        }
        pixels
    }

    /// The parameters of the pass are the coefficients of the colour
    /// space of the frame.
    #[test]
    fn the_parameters_of_the_pass_are_the_coefficients_of_the_colour_space() {
        for colorspace in colorspaces() {
            let params = YuvParams::new(colorspace);
            let coefficients = colorspace.coefficients();

            assert_eq!(params.y_scale, coefficients.y_scale);
            assert_eq!(params.y_offset, coefficients.y_offset);
            assert_eq!(params.u_offset, coefficients.u_offset);
            assert_eq!(params.v_offset, coefficients.v_offset);
            assert_eq!(params.crv, coefficients.crv);
            assert_eq!(params.cgu, coefficients.cgu);
            assert_eq!(params.cgv, coefficients.cgv);
            assert_eq!(params.cbu, coefficients.cbu);
        }
    }

    /// The shader reads the parameters under the names the Rust side
    /// writes them.
    #[test]
    fn the_shader_reads_the_parameters_of_the_pass() {
        for name in [
            "y_scale", "y_offset", "u_offset", "v_offset", "crv", "cgu", "cgv", "cbu",
        ] {
            assert!(
                SHADER.contains(name),
                "the shader must read the parameter `{name}`"
            );
        }
    }

    /// The conversion of the shader is the one of the parser.
    ///
    /// The shader combines the planes with the matrix of the colour space
    /// and samples the chroma with the nearest neighbour: the pixels it
    /// produces have to be the ones the CPU conversion produces.
    #[test]
    fn the_conversion_of_the_shader_is_the_one_of_the_parser() {
        let width = 8u32;
        let height = 4u32;
        let y: Vec<u8> = (0..width * height)
            .map(|value| (value * 7 % 256) as u8)
            .collect();
        let u: Vec<u8> = (0..width / 2 * height / 2)
            .map(|value| (value * 13 % 256) as u8)
            .collect();
        let v: Vec<u8> = (0..width / 2 * height / 2)
            .map(|value| (value * 29 % 256) as u8)
            .collect();

        for colorspace in colorspaces() {
            let expected = reference(width, height, &y, &u, &v, colorspace);
            let converted =
                yuv420_to_rgba(width, height, &y, &u, &v, colorspace).expect("no pixels");

            assert_eq!(
                converted, expected,
                "the conversion of {colorspace:?} differs"
            );
        }
    }

    /// The sRGB transfer function of the shader is the standard one.
    #[test]
    fn the_srgb_transfer_function_is_the_standard_one() {
        assert!(srgb_to_linear(0.0).abs() < 1e-6);
        assert!((srgb_to_linear(1.0) - 1.0).abs() < 1e-6);

        // The middle of the range is 0.2140 in the linear space.
        let middle = srgb_to_linear(0.5);
        assert!(
            (middle - 0.214041).abs() < 1e-5,
            "unexpected value {middle}"
        );

        // The linear and the encoded value are the same below the cutoff.
        let low = srgb_to_linear(0.03);
        assert!((low - 0.03 / 12.92).abs() < 1e-6, "unexpected value {low}");
    }

    /// The sRGB transfer function, in Rust.
    fn srgb_to_linear(color: f32) -> f32 {
        if color <= 0.04045 {
            color / 12.92
        } else {
            ((color + 0.055) / 1.055).powf(2.4)
        }
    }
}
